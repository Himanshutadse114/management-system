const MAPS = { hi: HI, mr: MR };

function replaceVars(text, vars) {
  return Object.entries(vars || {}).reduce((value, [key, replacement]) => value.replaceAll(`{${key}}`, String(replacement)), text);
}

export function publicMenuText(locale, key, vars = {}) {
  const dictionary = UI[locale] || UI.en;
  return replaceVars(dictionary[key] || UI.en[key] || key, vars);
}

export function localizeMenuValue(locale, value) {
  if (value == null || locale === 'en') return value;
  const source = String(value);
  const exact = MAPS[locale]?.[source];
  if (exact) return exact;

  const alcoholSuffix = ' · served at current outlet prices.';
  if (source.endsWith(alcoholSuffix)) {
    const brand = source.slice(0, -alcoholSuffix.length);
    const localBrand = MAPS[locale]?.[brand] || brand;
    return locale === 'hi'
      ? `${localBrand} · मौजूदा आउटलेट कीमतों पर उपलब्ध।`
      : `${localBrand} · सध्याच्या आउटलेट किंमतींवर उपलब्ध.`;
  }

  return source;
}

export function localizeMenuItem(locale, item) {
  if (!item) return item;
  return {
    ...item,
    _sectionKey: item.sectionName || 'Menu',
    _source: item,
    displayName: localizeMenuValue(locale, item.displayName),
    description: localizeMenuValue(locale, item.description),
    sectionName: localizeMenuValue(locale, item.sectionName || 'Menu'),
    dietaryTags: (item.dietaryTags || []).map((tag) => localizeMenuValue(locale, tag)),
    product: item.product ? {
      ...item.product,
      name: localizeMenuValue(locale, item.product.name),
      brand: localizeMenuValue(locale, item.product.brand),
      priceOptions: (item.product.priceOptions || []).map((price) => ({ ...price, label: localizeMenuValue(locale, price.label) }))
    } : item.product
  };
}

export function localeNumber(locale, value) {
  const tag = locale === 'hi' ? 'hi-IN-u-nu-deva' : locale === 'mr' ? 'mr-IN-u-nu-deva' : 'en-IN';
  try { return new Intl.NumberFormat(tag).format(Number(value)); } catch (_) { return String(value); }
}

export function localeMoney(locale, minor) {
  const tag = locale === 'hi' ? 'hi-IN-u-nu-deva' : locale === 'mr' ? 'mr-IN-u-nu-deva' : 'en-IN';
  try {
    return new Intl.NumberFormat(tag, { style: 'currency', currency: 'INR', minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(Number(minor || 0) / 100);
  } catch (_) {
    return `₹${Number(minor || 0) / 100}`;
  }
}
